"""Build an 8x16 CP866 font blob from GNU Unifont.

Unifont ships "<codepoint>:<hex rows>". We pull the 8px-wide glyphs for the
whole CP866 codepage (what a Russian DOS game in 1994 would have had) and emit
a 256*16 byte table. No CP866 here means no Russian, and no Russian means
no jokes, and then what is the point.
"""
import gzip
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vendor  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "build", "gen", "font.c")


def load_unifont(path):
    glyphs = {}
    with gzip.open(path, "rt", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            cp, data = line.split(":")
            glyphs[int(cp, 16)] = data
    return glyphs


def to_8x16(data):
    rows = [int(data[i:i + 2], 16) for i in range(0, len(data), 2)]
    if len(rows) == 16:
        return rows
    if len(rows) == 32:          # 16 wide: keep the right half
        return [rows[i * 2 + 1] for i in range(16)]
    return None


def main():
    path = vendor.unifont()
    if not path:
        raise SystemExit("unifont.hex.gz not found; run tools/setup.py")
    uf = load_unifont(path)
    table = bytearray(256 * 16)
    missing = []
    for code in range(32, 256):
        try:
            ch = bytes([code]).decode("cp866")
        except UnicodeDecodeError:
            continue
        rows = uf.get(ord(ch))
        r = to_8x16(rows) if rows else None
        if r is None:
            missing.append((code, ch))
            continue
        table[code * 16:code * 16 + 16] = bytes(r)
    if missing:
        print("missing glyphs:", missing[:12], file=sys.stderr)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="ascii") as f:
        f.write("/* generated by tools/genfont.py - GNU Unifont, CP866 layout */\n")
        f.write("#include \"assets.h\"\n")
        f.write("const unsigned char g_font[256*16] = {\n")
        for code in range(256):
            row = table[code * 16:code * 16 + 16]
            f.write("  " + ",".join("0x%02x" % b for b in row) + ",  /* %d */\n" % code)
        f.write("};\n")
    print("wrote font.c (%d bytes)" % len(table))


if __name__ == "__main__":
    main()

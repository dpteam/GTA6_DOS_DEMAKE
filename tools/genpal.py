"""Emit build/gen/pal.h and build/gen/paldata.c from pal.py.

pal.h     -> PAL_NEONPINK4 and friends, so C never sees a magic number.
paldata.c -> the 768-byte DAC table the VGA actually eats.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pal  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, "build", "gen")


def main():
    os.makedirs(GEN, exist_ok=True)
    lines = ["/* generated by tools/genpal.py - do not edit */",
             "#ifndef GTA_PAL_H",
             "#define GTA_PAL_H",
             "",
             "#define PAL_TRANSPARENT 0",
             "#define PAL_BLACK 0"]
    for name, idx in pal.PAL.items():
        lines.append("#define PAL_%s %d" % (name.upper(), idx))
    lines.append("")
    for name, (stops, n) in pal.RAMPS.items():
        lines.append("#define PAL_%s_BASE %d" % (name.upper(), pal.PAL[name + "0"]))
        lines.append("#define PAL_%s_N %d" % (name.upper(), n))
    lines.append("")
    lines.append("#define PAL_SHADOW PAL_VOID1")
    lines.append("#define PAL_TEXT PAL_WHITE6")
    lines.append("#define PAL_TEXT_DIM PAL_CONCRETE4")
    lines.append("")
    lines.append("#endif")
    with open(os.path.join(GEN, "pal.h"), "w", encoding="ascii") as f:
        f.write("\n".join(lines) + "\n")

    data = pal.pal_rgb()
    with open(os.path.join(GEN, "paldata.c"), "w", encoding="ascii") as f:
        f.write("/* generated by tools/genpal.py - do not edit */\n")
        f.write("#include \"assets.h\"\n")
        pal.emit_c_array(f, "g_pal", data, 16)
    print("wrote pal.h (%d entries) and paldata.c" % len(pal.PAL))


if __name__ == "__main__":
    main()

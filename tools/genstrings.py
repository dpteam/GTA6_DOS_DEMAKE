def c_lit(s):
    out = []
    for b in s.encode("cp866"):
        if b == 0x22:
            out.append('\\"')
        elif b == 0x5C:
            out.append("\\\\")
        elif 32 <= b < 127:
            out.append(chr(b))
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    lines = ["/* generated by tools/genstrings.py - do not edit */",
             "#ifndef GTA_STRINGS_H",
             "#define GTA_STRINGS_H",
             ""]
    for k, v in S.items():
        lines.append("#define S_%s %s" % (k, c_lit(v)))
    lines.append("")
    lines.append("#endif")
    with open(OUT, "w", encoding="ascii") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote strings.h (%d strings)" % len(S))


if __name__ == "__main__":
    main()
